#!/usr/bin/env node
/**
 * Generates `packages/shared/src/api/generated/openapi.d.ts` from the published
 * OpenAPI contract. The artifact is committed so typechecking never needs the
 * contract package; CI re-runs this script with `--check` to catch drift.
 *
 * Spec resolution order:
 *   1. `--spec <path>`
 *   2. `API_SPEC_PATH` environment variable
 *   3. `node_modules/@dauphaihau-camille/api-spec/openapi.json`
 *
 * Usage:
 *   bun ./scripts/generate-api-types.mjs
 *   bun ./scripts/generate-api-types.mjs --spec ../api/api/openapi.json
 *   bun ./scripts/generate-api-types.mjs --check
 */
import {
  existsSync, mkdirSync, readFileSync, writeFileSync, 
} from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = resolve(repoRoot, 'packages/shared/src/api/generated/openapi.d.ts');
const PACKAGE_NAME = '@dauphaihau-camille/api-spec';
const PACKAGE_SPEC = resolve(repoRoot, `node_modules/${PACKAGE_NAME}/openapi.json`);
const HEADER = `// Generated by scripts/generate-api-types.mjs from ${PACKAGE_NAME}. Do not edit.`;

/** Arguments after a forwarded `--` separator, if any. */
const args = process.argv.slice(2).filter((arg) => arg !== '--');
const checkOnly = args.includes('--check');

function readOption(name) {
  const index = args.indexOf(name);
  if (index === -1) return undefined;

  const value = args[index + 1];
  if (!value || value.startsWith('--')) {
    console.error(`error: ${name} requires a path argument`);
    process.exit(1);
  }

  return value;
}

function resolveSpec() {
  const flag = readOption('--spec');
  const envPath = process.env.API_SPEC_PATH;

  const candidates = [];
  if (flag) candidates.push({ label: '--spec <path>', path: resolve(process.cwd(), flag) });
  if (envPath) {
    candidates.push({ label: 'API_SPEC_PATH', path: resolve(process.cwd(), envPath) });
  }
  candidates.push({ label: 'published package', path: PACKAGE_SPEC });

  const found = candidates.find((candidate) => existsSync(candidate.path));
  if (found) return found;

  const describe = (label, path) =>
    path === undefined
      ? `  ${label.padEnd(21)} (not provided)`
      : `  ${label.padEnd(21)} ${path} (missing)`;

  console.error(
    [
      'Could not resolve the OpenAPI spec file.',
      'Tried, in order:',
      describe('--spec <path>', flag ? resolve(process.cwd(), flag) : undefined),
      describe('API_SPEC_PATH', envPath ? resolve(process.cwd(), envPath) : undefined),
      describe('published package', PACKAGE_SPEC),
      `Install ${PACKAGE_NAME} with NODE_AUTH_TOKEN that has read:packages (see .npmrc).`,
    ].join('\n'),
  );
  process.exit(1);
}

function normaliseNewlines(value) {
  return value.replace(/\r\n?/g, '\n');
}

function splitLines(value) {
  const lines = normaliseNewlines(value).split('\n');
  if (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return lines;
}

function firstDifference(committed, generated) {
  const committedLines = splitLines(committed);
  const generatedLines = splitLines(generated);
  const max = Math.max(committedLines.length, generatedLines.length);

  for (let index = 0; index < max; index += 1) {
    const before = committedLines[index];
    const after = generatedLines[index];
    if (before === after) continue;

    let column = 0;
    const limit = Math.min(before?.length ?? 0, after?.length ?? 0);
    while (column < limit && before[column] === after[column]) column += 1;

    return {
      line: index + 1,
      column: column + 1,
      before: before ?? '<end of file>',
      after: after ?? '<end of file>',
    };
  }

  return null;
}

function countLineChanges(committed, generated) {
  const remaining = new Map();
  for (const line of splitLines(committed)) {
    remaining.set(line, (remaining.get(line) ?? 0) + 1);
  }

  let added = 0;
  for (const line of splitLines(generated)) {
    const count = remaining.get(line) ?? 0;
    if (count > 0) {
      remaining.set(line, count - 1);
    }
    else {
      added += 1;
    }
  }

  let removed = 0;
  for (const count of remaining.values()) removed += count;

  return { added, removed };
}

async function render(specPath) {
  const schema = JSON.parse(readFileSync(specPath, 'utf8'));
  const ast = await openapiTS(schema, { silent: true, defaultNonNullable: false });
  const generated = `${HEADER}\n\n${astToString(ast)}`;
  return `${normaliseNewlines(generated).replace(/\n*$/, '')}\n`;
}

async function main() {
  const spec = resolveSpec();
  const content = await render(spec.path);
  const relativeOutput = OUTPUT_PATH.slice(repoRoot.length + 1);

  if (!checkOnly) {
    mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
    writeFileSync(OUTPUT_PATH, content, 'utf8');
    console.log(`wrote ${relativeOutput} from ${spec.label} (${splitLines(content).length} lines)`);
    return;
  }

  if (!existsSync(OUTPUT_PATH)) {
    console.error(`drift: ${relativeOutput} does not exist; run \`bun run generate:api-types\`.`);
    process.exit(1);
  }

  const committed = readFileSync(OUTPUT_PATH, 'utf8');
  if (normaliseNewlines(committed) === content) {
    console.log(`up to date: ${relativeOutput}`);
    return;
  }

  const diff = firstDifference(committed, content);
  const { added, removed } = countLineChanges(committed, content);
  console.error(`drift: ${relativeOutput} is out of date; run \`bun run generate:api-types\`.`);
  if (diff) {
    console.error(
      `  first difference at line ${diff.line}, column ${diff.column}\n` +
        `  - ${diff.before}\n` +
        `  + ${diff.after}`,
    );
  }
  console.error(`  added lines: ${added}, removed lines: ${removed}`);
  process.exit(1);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
